/**
 * Sanitize text for email content by removing problematic characters
 * @param text Text to sanitize
 * @returns Sanitized text
 */
export function sanitizeForEmail(text: string): string {
  if (!text) return '';
  
  // Replace problematic characters that might cause issues with email rendering
  return text
    .replace(/[\u0000-\u001F\u007F-\u009F]/g, '') // Remove control characters
    .replace(/[\u2028\u2029]/g, ' ') // Replace line/paragraph separators
    .replace(/[\uFFFE\uFFFF\uFFF0-\uFFFD]/g, '') // Remove Unicode BOM and specials
    .replace(/[\u0080-\u00A0]/g, ' ') // Replace Latin-1 control chars with spaces
    .trim();
}

/**
 * Generate a plain text version of the email
 * @param summaries List of filing summaries
 * @param errors List of errors encountered
 * @returns Plain text email content
 */
export function generatePlainTextEmail(
  summaries: FilingSummary[] | FilingSummaryResult[], 
  errors: FilingError[] = []
): string {
  let text = `SEC Filing Summaries - ${new Date().toLocaleDateString()}\n\n`;
  
  // Group by ticker
  const tickerMap: Record<string, FilingSummary[] | FilingSummaryResult[]> = {};
  
  summaries.forEach(summary => {
    if (!tickerMap[summary.ticker]) {
      tickerMap[summary.ticker] = [];
    }
    tickerMap[summary.ticker].push(summary);
  });
  
  // Generate text for each ticker
  Object.entries(tickerMap).forEach(([ticker, tickerSummaries]) => {
    text += `${ticker} - ${tickerSummaries[0].companyName}\n`;
    text += '='.repeat(40) + '\n\n';
    
    tickerSummaries.forEach(summary => {
      const formMetadata = getFormMetadata(summary.filingType);
      const formName = formMetadata ? formMetadata.displayName : summary.filingType;
      const filingDate = new Date(summary.filingDate).toLocaleDateString();
      
      text += `${formName} - Filed on ${filingDate}\n\n`;
      text += `${summary.summaryText}\n\n`;
      
      if (summary.keyPoints && summary.keyPoints.length > 0) {
        text += 'Key Points:\n';
        summary.keyPoints.forEach(point => {
          text += `- ${point}\n`;
        });
        text += '\n';
      }
      
      text += `View on SEC Website: ${summary.url}\n\n`;
    });
  });
  
  // Add errors if any
  if (errors.length > 0) {
    text += '\nIssues Encountered:\n';
    errors.forEach(err => {
      text += `${err.ticker}: ${err.error}\n`;
    });
  }
  
  // Add footer
  text += '\n--\n';
  text += 'This email was generated by tldrSEC. The information provided is for informational purposes only and should not be considered financial advice.\n';
  text += `© ${new Date().getFullYear()} tldrSEC`;
  
  return text;
}

