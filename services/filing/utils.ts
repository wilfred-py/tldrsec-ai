/**
 * Generate a simple summary based on parsed content
 * This is a fallback when AI summarization is not available
 */
export function generateSimpleSummary(
  parsedContent: ParsedContent, 
  formType: FilingType, 
  ticker: string, 
  companyName: string
): string {
  const formMetadata = getFormMetadata(formType);
  const formName = formMetadata ? formMetadata.displayName : formType;
  
  let summary = `This is a ${formName} filing from ${companyName} (${ticker}). `;
  
  if (parsedContent.title) {
    summary += `The filing is titled "${parsedContent.title}". `;
  }
  
  if (parsedContent.filingDate) {
    const filingDate = new Date(parsedContent.filingDate).toLocaleDateString();
    summary += `It was filed on ${filingDate}. `;
  }
  
  if (parsedContent.sections && parsedContent.sections.length > 0) {
    summary += `The document contains ${parsedContent.sections.length} major sections. `;
    
    // Add information about important sections if available
    const importantSections = ['Management Discussion', 'Risk Factors', 'Financial Statements'];
    const foundSections = parsedContent.sections
      .filter(section => importantSections.some(keyword => section.title.includes(keyword)))
      .map(section => section.title);
    
    if (foundSections.length > 0) {
      summary += `Key sections include: ${foundSections.join(', ')}. `;
    }
  }
  
  summary += `Please review the original filing for complete details.`;
  
  return summary;
}

/**
 * Extract key points from parsed content
 */
export function extractKeyPoints(parsedContent: ParsedContent, formType: FilingType): string[] {
  const keyPoints: string[] = [];
  
  // Try to extract key points from the parsed content
  if (parsedContent.sections) {
    // Look for sections that might contain key information
    const importantSections = parsedContent.sections.filter(section => {
      const title = section.title.toLowerCase();
      return (
        title.includes('summary') ||
        title.includes('highlight') ||
        title.includes('overview') ||
        title.includes('management') ||
        title.includes('discussion') ||
        title.includes('analysis') ||
        title.includes('risk factor') ||
        title.includes('financial')
      );
    });
    
    // Extract first paragraph from each important section
    importantSections.forEach(section => {
      if (section.content && section.content.length > 0) {
        // Get first paragraph that's not too short
        const paragraphs = section.content.split('\n\n');
        const significantParagraphs = paragraphs.filter(p => p.length > 100);
        
        if (significantParagraphs.length > 0) {
          // Extract a key point from the first significant paragraph
          const firstPara = significantParagraphs[0];
          const sentences = firstPara.split(/[.!?]+/).filter(s => s.trim().length > 0);
          
          if (sentences.length > 0) {
            const keyPoint = `${section.title}: ${sentences[0].trim()}.`;
            keyPoints.push(keyPoint);
          }
        }
      }
    });
  }
  
  // If we couldn't extract meaningful key points, provide generic ones
  if (keyPoints.length === 0) {
    const formMetadata = getFormMetadata(formType);
    
    if (formType === '10-K' || formType === '10-K/A') {
      keyPoints.push('Annual report containing audited financial statements.');
      keyPoints.push('Provides a comprehensive overview of the company\'s business and financial condition.');
      keyPoints.push('Includes management\'s discussion and analysis of financial condition and results of operations.');
    } else if (formType === '10-Q' || formType === '10-Q/A') {
      keyPoints.push('Quarterly report containing unaudited financial statements.');
      keyPoints.push('Provides a continuing view of the company\'s financial position during the year.');
      keyPoints.push('Less detailed than annual reports on Form 10-K.');
    } else if (formType === '8-K') {
      keyPoints.push('Current report announcing major events that shareholders should know about.');
      keyPoints.push('Filed to disclose material events or corporate changes.');
      keyPoints.push('Review the full filing for specific details about the reported event.');
    } else {
      keyPoints.push(`This is a ${formMetadata?.displayName || formType} filing.`);
      keyPoints.push('Review the full filing for complete details.');
      keyPoints.push('Consult with a financial advisor for interpretation of this document.');
    }
  }
  
  return keyPoints;
}
