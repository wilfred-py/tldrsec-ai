// Test script for email summary functionality with enhanced logging
import { PrismaClient } from './lib/generated/prisma/index.js';
import dotenv from 'dotenv';

// Load environment variables
dotenv.config();

// Initialize Prisma client
const prisma = new PrismaClient();

// Suppress Prisma query logs to reduce console clutter
prisma.$on('query', () => {
  // Do nothing with the query event
});

async function testEmailSummary() {
  console.log('===== TESTING EMAIL SUMMARY FUNCTIONALITY =====');
  
  try {
    // Replace with a valid email address for testing
    const testEmail = 'test@example.com';
    
    // Get some tickers from the database to test with
    console.log('Fetching tickers from database...');
    const dbTickers = await prisma.ticker.findMany({
      take: 3, // Limit to 3 tickers for testing
      orderBy: { addedAt: 'desc' }
    });
    
    if (!dbTickers || dbTickers.length === 0) {
      console.log('No tickers found in database. Using default test tickers.');
      var tickers = ['AAPL', 'MSFT', 'GOOGL'];
    } else {
      var tickers = dbTickers.map(t => t.symbol);
      console.log(`Found ${tickers.length} tickers in database: ${tickers.join(', ')}`);
    }
    
    // Verify we can fetch summaries for these tickers
    console.log('\n===== VERIFYING SUMMARY RETRIEVAL =====');
    const summaries = [];
    const errors = [];
    
    for (const ticker of tickers) {
      try {
        console.log(`Checking summaries for ${ticker}...`);
        const tickerRecord = await prisma.ticker.findFirst({
          where: { symbol: ticker }
        });
        
        if (!tickerRecord) {
          console.warn(`WARNING: No ticker record found for ${ticker}`);
          errors.push({ ticker, error: 'Ticker not found in database' });
          continue;
        }
        
        // Get latest summary for this ticker
        const latestSummary = await prisma.summary.findFirst({
          where: { tickerId: tickerRecord.id },
          orderBy: { createdAt: 'desc' }
        });
        
        if (latestSummary) {
          console.log(`SUCCESS: Found summary for ${ticker} (${latestSummary.filingType})`);
          console.log(`Processing status: ${latestSummary.processingStatus || 'N/A'}`);
          console.log(`Summary text length: ${latestSummary.summaryText.length} chars`);
          summaries.push({
            ticker,
            filingType: latestSummary.filingType,
            summaryText: latestSummary.summaryText,
            processingStatus: latestSummary.processingStatus
          });
        } else {
          console.warn(`WARNING: No summary found for ${ticker}`);
          errors.push({ ticker, error: 'No summary found' });
        }
      } catch (tickerError) {
        console.error(`ERROR processing ${ticker}:`, tickerError);
        errors.push({ ticker, error: tickerError.message });
      }
    }
    
    // Generate email content for testing
    console.log('\n===== GENERATING TEST EMAIL CONTENT =====');
    if (summaries.length > 0) {
      console.log(`Generating email content for ${summaries.length} summaries...`);
      
      // Simple HTML email template
      const emailHtml = `
        <!DOCTYPE html>
        <html>
        <head>
          <style>
            body { font-family: Arial, sans-serif; line-height: 1.6; }
            .summary { margin-bottom: 30px; border-bottom: 1px solid #eee; padding-bottom: 20px; }
            h2 { color: #333; }
            .meta { color: #666; font-size: 0.9em; }
          </style>
        </head>
        <body>
          <h1>SEC Filing Summaries - ${new Date().toLocaleDateString()}</h1>
          ${summaries.map(summary => `
            <div class="summary">
              <h2>${summary.ticker} - ${summary.filingType}</h2>
              <div class="meta">Processing status: ${summary.processingStatus || 'N/A'}</div>
              <p>${summary.summaryText.substring(0, 300)}...</p>
            </div>
          `).join('')}
          <p>This is a test email generated by the test-email-summary.mjs script.</p>
        </body>
        </html>
      `;
      
      // Plain text version
      const plainText = `
        SEC Filing Summaries - ${new Date().toLocaleDateString()}
        
        ${summaries.map(summary => `
        ${summary.ticker} - ${summary.filingType}
        Processing status: ${summary.processingStatus || 'N/A'}
        
        ${summary.summaryText.substring(0, 300)}...
        
        ---
        `).join('\n')}
        
        This is a test email generated by the test-email-summary.mjs script.
      `;
      
      console.log('Email content generated successfully');
      console.log('\nHTML Preview (first 200 chars):');
      console.log(emailHtml.substring(0, 200) + '...');
      
      console.log('\nPlain Text Preview (first 200 chars):');
      console.log(plainText.substring(0, 200) + '...');
    } else {
      console.warn('No summaries available to generate email content');
    }
    
    // Analyze the result
    console.log('\n===== EMAIL SUMMARY TEST RESULTS =====');
    console.log(`Generated ${summaries.length} summaries`);
    console.log(`Encountered ${errors.length} errors`);
    
    // Display summary information
    if (summaries.length > 0) {
      console.log('\n===== SUMMARY DETAILS =====');
      for (const summary of summaries) {
        console.log(`- ${summary.ticker} (${summary.filingType}): ${summary.summaryText.substring(0, 100)}...`);
      }
    }
    
    // Display error information
    if (errors.length > 0) {
      console.log('\n===== ERROR DETAILS =====');
      for (const error of errors) {
        console.log(`- ${error.ticker}: ${error.error}`);
      }
    }
    
    console.log('\n===== TEST COMPLETED =====');
  } catch (error) {
    console.error('Error testing email summary:', error);
  } finally {
    // Close Prisma client to prevent hanging process
    await prisma.$disconnect();
  }
}

// Run the test
testEmailSummary().catch(error => {
  console.error('Unhandled error in test script:', error);
  prisma.$disconnect().then(() => process.exit(1));
});
