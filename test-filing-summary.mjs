// Test script to verify SEC filing summary functionality
import { PrismaClient } from './lib/generated/prisma/index.js';
import dotenv from 'dotenv';
import { Anthropic } from '@anthropic-ai/sdk';

// Load environment variables
dotenv.config();

// Initialize Prisma client
const prisma = new PrismaClient();

// Suppress Prisma query logs to reduce console clutter
prisma.$on('query', () => {
  // Do nothing with the query event
});

// Initialize Anthropic client
const anthropic = new Anthropic({
  apiKey: process.env.ANTHROPIC_API_KEY,
});

async function testFilingSummary() {
  console.log('===== TESTING SEC FILING SUMMARY FUNCTIONALITY =====');
  
  // Test ticker
  const ticker = 'AAPL';
  
  try {
    // 1. Get ticker from database
    console.log(`\nFetching ticker record for ${ticker}...`);
    let tickerRecord = await prisma.ticker.findFirst({
      where: { symbol: ticker }
    });
    
    if (!tickerRecord) {
      console.log(`Ticker ${ticker} not found in database. Creating it...`);
      tickerRecord = await prisma.ticker.create({
        data: {
          symbol: ticker,
          name: 'Apple Inc.',
          exchange: 'NASDAQ',
          addedAt: new Date(),
          lastCheckedAt: new Date()
        }
      });
      console.log(`Created ticker record for ${ticker}`);
    } else {
      console.log(`Found ticker record for ${ticker}`);
    }
    
    // 2. Get or create a test SEC filing
    console.log('\nFetching/creating test SEC filing...');
    let testFiling = await prisma.secFiling.findFirst({
      where: {
        tickerId: tickerRecord.id,
        formType: '10-K'
      },
      orderBy: {
        filingDate: 'desc'
      }
    });
    
    if (!testFiling) {
      console.log('No existing 10-K filing found. Creating a test filing...');
      testFiling = await prisma.secFiling.create({
        data: {
          tickerId: tickerRecord.id,
          formType: '10-K',
          filingDate: new Date(),
          secUrl: 'https://www.sec.gov/Archives/edgar/data/320193/000032019323000077/aapl-20230930.htm',
          accessionNumber: '000032019323000077',
          companyName: 'Apple Inc.',
          cik: '0000320193',
        }
      });
      console.log('Created test SEC filing');
    } else {
      console.log(`Found existing 10-K filing from ${testFiling.filingDate.toLocaleDateString()}`);
    }
    
    // 3. Create a test summary
    console.log('\nCreating test summary...');
    const testSummary = await prisma.summary.create({
      data: {
        tickerId: tickerRecord.id,
        secFilingId: testFiling.id,
        filingType: '10-K',
        filingDate: testFiling.filingDate,
        filingUrl: testFiling.secUrl,
        url: `https://www.sec.gov/ix?doc=/Archives/edgar/data/320193/000032019323000077/aapl-20230930.htm`,
        summaryText: 'This is a test summary for Apple Inc. 10-K filing.',
        summaryJSON: {
          summary: 'Test summary',
          keyPoints: ['Test point 1', 'Test point 2']
        },
        processingStatus: 'COMPLETED',
        processingCompletedAt: new Date(),
        processingTimeMs: 5000,
        tokensUsed: 1500,
        model: 'claude-3-haiku-20240307',
        cost: 0.015,
        attempts: 1,
        sentToUser: false
      }
    });
    console.log(`Created test summary with ID: ${testSummary.id}`);
    
    // 4. Verify URL format
    console.log('\nVerifying URL format...');
    console.log(`Filing URL: ${testSummary.filingUrl}`);
    console.log(`SEC HTML Viewer URL: ${testSummary.url}`);
    
    if (testSummary.url && testSummary.url.includes('/ix?doc=/')) {
      console.log('✅ URL format is correct (uses SEC HTML viewer format)');
    } else {
      console.log('❌ URL format is incorrect (should use SEC HTML viewer format)');
    }
    
    // 5. Generate email content for preview
    console.log('\nGenerating email content preview...');
    const emailHtml = `
      <!DOCTYPE html>
      <html>
      <head>
        <style>
          body { font-family: Arial, sans-serif; line-height: 1.6; }
          .summary { margin-bottom: 30px; border-bottom: 1px solid #eee; padding-bottom: 20px; }
          h2 { color: #333; }
          .meta { color: #666; font-size: 0.9em; }
        </style>
      </head>
      <body>
        <h1>SEC Filing Summary - ${testSummary.filingDate.toLocaleDateString()}</h1>
        <div class="summary">
          <h2>${ticker} - ${testSummary.filingType}</h2>
          <div class="meta">Processing status: ${testSummary.processingStatus}</div>
          <p>${testSummary.summaryText}</p>
          <p><a href="${testSummary.url}">View original filing</a></p>
        </div>
        <p>This is a test email generated by the test-filing-summary.mjs script.</p>
      </body>
      </html>
    `;
    
    // Plain text version
    const plainText = `
      SEC Filing Summary - ${testSummary.filingDate.toLocaleDateString()}
      
      ${ticker} - ${testSummary.filingType}
      Processing status: ${testSummary.processingStatus}
      
      ${testSummary.summaryText}
      
      View original filing: ${testSummary.url}
      
      This is a test email generated by the test-filing-summary.mjs script.
    `;
    
    console.log('Email content generated successfully');
    console.log('\nHTML Preview (first 200 chars):');
    console.log(emailHtml.substring(0, 200) + '...');
    
    console.log('\nPlain Text Preview (first 200 chars):');
    console.log(plainText.substring(0, 200) + '...');
    
    // 6. Clean up test data
    console.log('\n===== CLEANING UP TEST DATA =====');
    console.log('Deleting test summary...');
    await prisma.summary.delete({
      where: { id: testSummary.id }
    });
    console.log('Test summary deleted');
    
    console.log('\n===== TEST COMPLETED SUCCESSFULLY =====');
  } catch (error) {
    console.error('Error testing filing summary:', error);
  } finally {
    // Close Prisma client to prevent hanging process
    await prisma.$disconnect();
  }
}

// Run the test
testFilingSummary().catch(error => {
  console.error('Unhandled error in test script:', error);
  prisma.$disconnect().then(() => process.exit(1));
});
